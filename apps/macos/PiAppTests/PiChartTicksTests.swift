    func testDateTicksAreSwiftCharts() {
        var calendar = Calendar(identifier: .gregorian)
        calendar.timeZone = TimeZone(secondsFromGMT: 8 * 3_600)!
        calendar.locale = Locale(identifier: "en_US")
        let offset = Date.timeIntervalBetween1970AndReferenceDate
        for (from, until, expected) in Self.dates {
            let ticks = PiChartTicks.dates((from - offset)...(until - offset), calendar: calendar).map { ($0 + offset).rounded() }
            XCTAssertEqual(ticks, expected, "span \(until - from) s")
        }
