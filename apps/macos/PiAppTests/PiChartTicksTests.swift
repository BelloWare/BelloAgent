    func testNumberDomainsAndStepsAreSwiftCharts() {
        for (top, desired, end, step) in Self.numbers {
            let (domain, step0) = PiChartTicks.automaticDomain(0, top, desiredCount: desired)
            XCTAssertEqual(domain.upperBound, end, accuracy: end * 1e-9, "top \(top) desired \(desired.map(String.init) ?? "-")")
            let ticks = PiChartTicks.multiples(of: step0, in: domain)
            XCTAssertEqual(ticks.count > 1 ? ticks[1] - ticks[0] : 0, step, accuracy: step * 1e-9, "top \(top) desired \(desired.map(String.init) ?? "-")")
            XCTAssertEqual(ticks.first, 0); XCTAssertFalse(ticks.first?.sign == .minus, "no -0")
        }
    }

    /// `.automatic(includesZero: false)`: the data's own span, on its ticks, not from zero.
    func testAnAxisOffZeroKeepsToItsData() {
        let (domain, step) = PiChartTicks.automaticDomain(103, 118, desiredCount: nil, includesZero: false)
        XCTAssertGreaterThan(domain.lowerBound, 0)
        XCTAssertLessThanOrEqual(domain.lowerBound, 103); XCTAssertGreaterThanOrEqual(domain.upperBound, 118)
        XCTAssertEqual(domain.lowerBound.truncatingRemainder(dividingBy: step), 0, accuracy: 1e-9)
        XCTAssertEqual(PiChartTicks.automaticDomain(0, 118, desiredCount: nil, includesZero: false).domain.lowerBound, 0)
    }

